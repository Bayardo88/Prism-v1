/**
 * Checks that every frame in the Scalar-full-product Figma file is coded as
 * exactly one screen state, then writes the screen catalog:
 *
 *   docs/product/screen-catalog.md   — human-readable, one table per Figma page
 *   docs/product/screens.json        — machine-readable, read by the scalar-product skill
 *
 * Run after `npm run build:product` (it imports the compiled registry):
 *   npm run product:catalog
 *
 * Exits non-zero when a frame is missing, duplicated, mislabelled, or when a
 * state points at a node that is not in the manifest — so CI can hold the line.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(root, 'apps/product/figma-frames.json'), 'utf8'));
const { allScreens } = await import(join(root, 'apps/product/build/registry.js'));

const FIGMA = `https://www.figma.com/design/${manifest.fileKey}/${manifest.fileName}?node-id=`;
const figmaUrl = (node) => FIGMA + node.replace(':', '-');
const example = (route) => route.replace(':companyId', 'abc-co');

/* --- coverage ------------------------------------------------------------ */

const errors = [];
const coded = new Map();
for (const s of allScreens) {
  for (const st of s.states) {
    if (coded.has(st.figmaNode)) errors.push(`${st.figmaNode} is coded twice (${coded.get(st.figmaNode).screen.id} and ${s.id})`);
    coded.set(st.figmaNode, { screen: s, state: st });
  }
  const keys = s.states.map((st) => st.key);
  if (new Set(keys).size !== keys.length) errors.push(`${s.id} has duplicate state keys`);
  if (!s.states.length) errors.push(`${s.id} has no states`);
}
const ids = allScreens.map((s) => s.id);
for (const id of ids.filter((id, i) => ids.indexOf(id) !== i)) errors.push(`screen id ${id} is used twice`);

const known = new Set(manifest.frames.map((f) => f.node));
for (const f of manifest.frames) {
  const hit = coded.get(f.node);
  if (!hit) errors.push(`missing: ${f.node} "${f.name}" (${f.page})`);
  else if (hit.state.label !== f.name) errors.push(`label drift: ${f.node} is "${f.name}" in Figma, "${hit.state.label}" in code`);
}
// Prototype states carry `proto:<name>:<n>` instead of a Figma node.
for (const node of coded.keys()) {
  if (!known.has(node) && !node.startsWith('proto:')) errors.push(`unknown node ${node} — not in figma-frames.json`);
}

/* --- catalog ------------------------------------------------------------- */

const pages = [...new Set(manifest.frames.map((f) => f.page))];
let md = `# Screen catalog

Generated by \`scripts/gen-product-catalog.mjs\` — do not edit by hand.

**${allScreens.length} screens · ${coded.size} of ${manifest.frames.length} Figma frames coded** · Figma file
[${manifest.fileName}](https://www.figma.com/design/${manifest.fileKey}/${manifest.fileName}).
Open any row in the running app at \`apps/product/index.html#<route>?state=<key>\`,
or jump straight from a Figma node with \`#/figma/<node-id>\`.

`;

for (const page of pages) {
  md += `## ${page}\n\n| Figma frame | Screen · state | Route | Component |\n|---|---|---|---|\n`;
  for (const f of manifest.frames.filter((x) => x.page === page)) {
    const hit = coded.get(f.node);
    if (!hit) { md += `| [${f.name}](${figmaUrl(f.node)}) | **not coded** | | |\n`; continue; }
    const { screen, state } = hit;
    const isDefault = screen.states[0] === state;
    const route = `\`${example(screen.route)}${isDefault ? '' : `?state=${state.key}`}\``;
    md += `| [${f.name}](${figmaUrl(f.node)}) | ${screen.title} · \`${state.key}\` | ${route} | \`${screen.component.name}\` · \`${screen.id}\` |\n`;
  }
  md += '\n';
}

const protos = allScreens.filter((s) => s.states.some((st) => st.figmaNode.startsWith('proto:')));
if (protos.length) {
  md += `## Prototypes (not in Figma)\n\n| Screen · state | Route |\n|---|---|\n`;
  for (const s of protos) for (const st of s.states) md += `| ${s.title} · \`${st.key}\` | \`${example(s.route)}?state=${st.key}\` |\n`;
  md += '\n';
}

const json = allScreens.map((s) => ({
  id: s.id,
  title: s.title,
  figmaPage: s.figmaPage,
  route: s.route,
  summary: s.summary,
  component: s.component.name,
  states: s.states.map((st) => ({ ...st, figmaUrl: st.figmaNode.startsWith('proto:') ? null : figmaUrl(st.figmaNode) })),
}));

mkdirSync(join(root, 'docs/product'), { recursive: true });
writeFileSync(join(root, 'docs/product/screen-catalog.md'), md);
writeFileSync(join(root, 'docs/product/screens.json'), JSON.stringify(json, null, 2) + '\n');

if (errors.length) {
  console.error(`✗ ${errors.length} coverage problem(s):\n  ` + errors.join('\n  '));
  process.exit(1);
}
console.log(`✓ all ${manifest.frames.length} Figma frames coded across ${allScreens.length} screens — catalog written`);
